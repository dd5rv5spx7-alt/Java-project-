package com.agrocti.export;

import com.agrocti.config.Config;
import com.agrocti.data.Dataset;
import com.agrocti.data.FeatureExtractor;
import com.agrocti.data.MoistureModel;
import com.agrocti.data.Scaler;
import com.agrocti.ml.QuantizedAutoencoder;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Writes the int8 model as a C header for the ESP32 firmware, plus a header of test vectors
 * (raw readings, the features and score Java computes) so the C code can be checked on a PC.
 */
public final class CHeaderExporter {

    private CHeaderExporter() { }

    private static String f(double v) {
        return String.format(Locale.ROOT, "%.9gf", v);
    }

    public static void writeModel(Path file, QuantizedAutoencoder q, Scaler scaler, MoistureModel mm,
                                  double tau, double tauLow) throws IOException {
        int[] sizes = q.getSizes();
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(file, StandardCharsets.UTF_8))) {
            w.println("/* Generated by Agro-CTI (com.agrocti.export.CHeaderExporter). Do not edit. */");
            w.println("#ifndef AGRO_AE_MODEL_H");
            w.println("#define AGRO_AE_MODEL_H");
            w.println("#include <stdint.h>");
            w.println();
            w.println("#define AE_LAYERS " + (sizes.length - 1));
            w.println("#define AE_DIM " + sizes[0]);
            w.println("#define AE_NF " + Config.NF);
            w.println("#define AE_WINDOW " + Config.WINDOW);
            w.println("#define AE_LONG_WINDOW " + Config.LONG_WINDOW);
            w.println("#define AE_STEPS_PER_DAY " + Config.STEPS_PER_DAY);
            w.print("static const int ae_sizes[" + sizes.length + "] = {");
            for (int i = 0; i < sizes.length; i++) w.print((i > 0 ? ", " : "") + sizes[i]);
            w.println("};");
            byte[][] wq = q.getWeights();
            int[][] bq = q.getBiases();
            for (int l = 0; l < wq.length; l++) {
                w.print("static const int8_t ae_w" + l + "[" + wq[l].length + "] = {");
                for (int i = 0; i < wq[l].length; i++) w.print((i % 24 == 0 ? "\n  " : "") + wq[l][i] + (i + 1 < wq[l].length ? "," : ""));
                w.println("\n};");
                w.print("static const int32_t ae_b" + l + "[" + bq[l].length + "] = {");
                for (int i = 0; i < bq[l].length; i++) w.print((i > 0 ? "," : "") + bq[l][i]);
                w.println("};");
            }
            w.print("static const int8_t *const ae_w[AE_LAYERS] = {");
            for (int l = 0; l < wq.length; l++) w.print((l > 0 ? ", " : "") + "ae_w" + l);
            w.println("};");
            w.print("static const int32_t *const ae_b[AE_LAYERS] = {");
            for (int l = 0; l < wq.length; l++) w.print((l > 0 ? ", " : "") + "ae_b" + l);
            w.println("};");
            array(w, "ae_w_scale", q.getWeightScales());
            array(w, "ae_act_scale", q.getActScales());
            array(w, "feat_mean", scaler.getMean());
            array(w, "feat_std", scaler.getStd());
            array(w, "balance_coef", mm.getCoefficients());
            w.println("static const float balance_residual_std = " + f(mm.getResidualStd()) + ";");
            w.println("static const float feat_clip = " + f(Scaler.CLIP) + ";");
            w.println("static const float ae_tau = " + f(tau) + ";");
            w.println("static const float ae_tau_low = " + f(tauLow) + ";");
            w.println();
            w.println("#endif");
        }
    }

    private static void array(PrintWriter w, String name, double[] a) {
        w.print("static const float " + name + "[" + a.length + "] = {");
        for (int i = 0; i < a.length; i++) w.print((i % 6 == 0 ? "\n  " : "") + f(a[i]) + (i + 1 < a.length ? ", " : ""));
        w.println("\n};");
    }

    /** Test vectors: for chosen (node, step) pairs, the raw readings and what Java computes. */
    public static void writeTestVectors(Path file, Dataset ds, FeatureExtractor fx, Scaler scaler,
                                        QuantizedAutoencoder q, int[][] picks) throws IOException {
        int rows = Config.LONG_WINDOW + 1;
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(file, StandardCharsets.UTF_8))) {
            w.println("/* Generated test vectors: Java reference results for the C implementation. */");
            w.println("#define TV_COUNT " + picks.length);
            w.println("#define TV_ROWS " + rows);
            w.println("static const int tv_step[TV_COUNT] = {");
            for (int[] p : picks) w.print(p[1] + ",");
            w.println("};");
            w.println("static const float tv_raw[TV_COUNT][TV_ROWS][AE_NF] = {");
            for (int[] p : picks) {
                w.print(" {");
                for (int r = 0; r < rows; r++) {
                    double[] v = ds.values[p[0]][p[1] - rows + 1 + r];
                    w.print("{");
                    for (int k = 0; k < v.length; k++) w.print(f(v[k]) + (k + 1 < v.length ? "," : ""));
                    w.print("}" + (r + 1 < rows ? "," : ""));
                }
                w.println("},");
            }
            w.println("};");
            w.println("static const float tv_features[TV_COUNT][AE_DIM] = {");
            for (int[] p : picks) {
                double[] z = scaler.transform(fx.extract(ds, p[0], p[1]));
                w.print(" {");
                for (int k = 0; k < z.length; k++) w.print(f(z[k]) + (k + 1 < z.length ? "," : ""));
                w.println("},");
            }
            w.println("};");
            w.println("static const float tv_score[TV_COUNT] = {");
            for (int[] p : picks) w.print(f(q.score(scaler.transform(fx.extract(ds, p[0], p[1])))) + ",");
            w.println("};");
        }
    }
}
